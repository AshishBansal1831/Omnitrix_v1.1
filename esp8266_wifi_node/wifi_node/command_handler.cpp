typedef uint8_t crc_t;

enum class CMD_DECODE_STATE 
{
    HEADER, // 2Bytes
    PACKET_NO,
    TOTAL_PACKETS,
    PACKET_ID, // 1 Byte
    PAYLOAD,
};

