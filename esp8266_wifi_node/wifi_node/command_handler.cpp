crc_t Packet::calc_crc(const uint8_t *buffer, size_t Len)
{
    crc_t Crc = 0;
    for(int Iter = 0; Iter < Len; ++Iter)
    {
        Crc ^= buffer[Iter];
    }

    return Crc;
}


