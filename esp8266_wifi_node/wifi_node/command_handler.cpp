crc_t calc_crc(const uint8_t *buffer, size_t Len)
{
    crc_t Crc = 0;
    for(int Iter = 0; Iter < Len; ++Iter)
    {
        Crc ^= buffer[Iter];
    }

    return Crc;
}

/*
 * return  length of bytes written (Index variable)
 */
uint16_t make_packet(uint8_t *payload, uint16_t length)
{
    uint16_t Index = 2;
    uint8_t Crc = 0;
    if(payload != NULL)
    {
        cmd_out_buffer[0] = 0xA5;
        cmd_out_buffer[1] = 0x5A;
        cmd_out_buffer[2] = 0;
        Index = 3;

        // 2 bytes Length
        Index += sizeof(length);

        //Payload
        memcpy(cmd_out_buffer + Index, payload, length);
        Index += length;

        cmd_out_buffer[2] = (Index >> 8) & 0xFF;
        cmd_out_buffer[3] = Index & 0xFF;

        // XOR CRC
        Crc= calc_crc(cmd_out_buffer, length);
        // printf("crc - %02X %d\r\n", Crc, length);
        cmd_out_buffer[Index] = Crc;
    }

    return Index + 1;
}

uint8_t check_cmd(const uint8_t Recv)
{
    static CMD_DECODE_STATE Decode_state = CMD_DECODE_STATE::HEADER;
    static size_t Index = 0;
    static uint16_t NumOfBytes = 0;
    Packet *packet = &G_Packets;
    
#ifdef DEBUG
   static CMD_DECODE_STATE prev_state = HEADER;
   if(prev_state != Decode_state)
   {
       printf("Decode_state - %d\r\n", Decode_state);
       prev_state = Decode_state;
   }
#endif

    switch(Decode_state)
    {
        case CMD_DECODE_STATE::HEADER:
            if(NumOfBytes == 0 && Recv == 0xA5)
            {
                NumOfBytes++;
            }
            else if(NumOfBytes == 1 && Recv == 0x5A)
            {
                Decode_state = CMD_DECODE_STATE::PACKET_NO;
                Index = 0;
                NumOfBytes = 0;
            }
            break;
        
        case CMD_DECODE_STATE::PACKET_NO:
            packet->Pkt_No = Recv;
            Decode_state = CMD_DECODE_STATE::TOTAL_PACKETS;
            break;
        
        case CMD_DECODE_STATE::TOTAL_PACKETS:
            packet->Totalno = Recv;
            Decode_state = CMD_DECODE_STATE::PACKET_ID;
            break;
        
        case CMD_DECODE_STATE::PACKET_ID:
            packet->PacketID = static_cast<PACKET_TYPE>(Recv);
            Decode_state = CMD_DECODE_STATE::PAYLOAD;
            NumOfBytes = 0;
            break;

        case CMD_DECODE_STATE::PAYLOAD:
            cmd_payload_buffer[Index++] = Recv;
            if(Index >= PAYLOAD_MAX_LENGTH)
            {
                Decode_state = CMD_DECODE_STATE::HEADER;
            }
            break;

        default:
            break;
    }

    return 0;
}

